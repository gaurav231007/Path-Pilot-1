    versionName = "1.0"

    testInstrumentationRunner = "androidx.test.runner.AndroidJUnitRunner"

    // Developer-only Gemini configuration. The actual value is read from
    // local.properties and that file is ignored by Git.
    val localProperties = Properties()
    val localPropertiesFile = rootProject.file("local.properties")
    if (localPropertiesFile.exists()) {
      localPropertiesFile.inputStream().use { localProperties.load(it) }
    }
    val geminiKey = localProperties.getProperty("GEMINI_API_KEY", "").trim()
      .replace("\\", "\\\\")
      .replace("\"", "\\\"")
    buildConfigField("String", "PATH_PILOT_GEMINI_API_KEY", "\"$geminiKey\"")
  }

  signingConfigs {
    create("release") {
      val keystorePath = System.getenv("KEYSTORE_PATH") ?: "${rootDir}/my-upload-key.jks"
      val keystoreFile = file(keystorePath)
      val debugFile = file("${rootDir}/debug.keystore")
      storeFile = if (keystoreFile.exists()) keystoreFile else if (debugFile.exists()) debugFile else null
      storePassword = System.getenv("STORE_PASSWORD") ?: "android"
      keyAlias = System.getenv("KEY_ALIAS") ?: "upload"
      keyPassword = System.getenv("KEY_PASSWORD") ?: "android"
    }
    create("debugConfig") {
      val debugFile = file("${rootDir}/debug.keystore")
      if (debugFile.exists()) {
        storeFile = debugFile
        storePassword = "android"
        keyAlias = "androiddebugkey"
        keyPassword = "android"
      }
    }
  }

  buildTypes {
    release {
      isCrunchPngs = false
      isMinifyEnabled = false
      proguardFiles(getDefaultProguardFile("proguard-android-optimize.txt"), "proguard-rules.pro")
      val keystorePath = System.getenv("KEYSTORE_PATH") ?: "${rootDir}/my-upload-key.jks"
      val keystoreFile = file(keystorePath)
      val debugFile = file("${rootDir}/debug.keystore")
      if (keystoreFile.exists()) {
        signingConfig = signingConfigs.getByName("release")
      } else if (debugFile.exists()) {
        signingConfig = signingConfigs.getByName("debugConfig")
      } else {
        signingConfig = signingConfigs.getByName("debug")
      }
    }
    debug {
      val debugFile = file("${rootDir}/debug.keystore")
      if (debugFile.exists()) {
        signingConfig = signingConfigs.getByName("debugConfig")
      } else {
        signingConfig = signingConfigs.getByName("debug")
      }
    }
  }
